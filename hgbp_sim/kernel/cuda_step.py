"""Benchmark prototype: the model's step on an NVIDIA GPU (CUDA C++, one thread per stand).

``kernel/cuda/hgbp_step.cu`` ports the step of :mod:`hgbp_sim.kernel.model`
(``step_batch``: sub-steps from the fastest local rate, implausible sub-steps redone
four times finer, the projections after every sub-step) with the property lookups
and the scalar components.  The CPU kernel stays the reference and is not changed;
nothing in the package imports this module.  See ``docs/gpu-benchmark.md``.

Precision modes:

* ``fp64``: everything in double precision (as the CPU kernel);
* ``fp32``: state, tables, right-hand side and projections in single precision;
* ``mixed``: single precision tables and right-hand side; double precision state,
  sub-step accumulation and projections (which read the single precision tables).

The source is compiled with ``nvcc`` on first use (CUDA toolkit: ``CUDA_HOME`` or
``/usr/local/cuda``) and cached in ``~/.cache/hgbp_sim/cuda``.  Before compiling, every
floating-point literal of the device code is written as ``R(literal)``, ``R`` being
each function's compute type, so that the float32 builds do not promote to double.
"""
from __future__ import annotations

import ctypes
import hashlib
import os
import re
import subprocess
from pathlib import Path

import numpy as np

from . import layout as L
from . import model as km
from . import props as kp
from .. import components as comp

MODES = {"fp64": 0, "fp32": 1, "mixed": 2}
_SRC = Path(__file__).with_name("cuda") / "hgbp_step.cu"
_LIT = re.compile(r"(?<![\w.])((?:\d+\.\d*|\.\d+)(?:[eE][+-]?\d+)?|\d+[eE][+-]?\d+)(?![\w.])")


def _header(launch_bounds) -> str:
    """hgbp_layout.h: state, parameter and table indices and the model's constants."""
    out = ["// generated by hgbp_sim.kernel.cuda_step; do not edit", "#pragma once"]
    out.append(f"#define NX {L.NX}")
    out.append(f"#define MX {L.MX}")
    out.append(f"#define NS {km.NS}")
    out.append(f"#define NPARAM {L.PARAM_DTYPE.itemsize // 8}")
    for name, i in L.IX.items():
        out.append(f"#define XI_{name} {i}")
    for name in L.PARAM_DTYPE.names:
        dt, off = L.PARAM_DTYPE.fields[name][:2]
        if dt.base != np.float64:
            raise TypeError(f"parameter {name} is not float64")
        out.append(f"#define PI_{name} {off // 8}")
    for k in ("T_L", "T_V", "H_L", "H_V", "RHO_L", "RHO_V", "S_L", "S_V", "CP_L", "CP_V", "DT_L_DP", "DH_L_DP",
              "DH_V_DP", "DRHO_L_DP", "DRHO_V_DP", "DHMAX_V", "DHMAX_L"):
        out.append(f"#define SAT_{k} {getattr(kp, k)}")
    for k in ("T", "RHO", "S", "DRHO_DP", "DRHO_DH", "CP"):
        out.append(f"#define REG_{k} {getattr(kp, 'R_' + k)}")
    for k in ("MU_L", "MU_V", "SIGMA"):
        out.append(f"#define TR_{k} {getattr(kp, k)}")
    for k in ("G", "DRYOUT_BAND", "STIFF_FILL", "LAM_DT_MAX", "MAX_DH_STEP", "MAX_DP_STEP", "CF_STAGNANT", "WET_BAND",
              "POOL_FULL", "FLOOD_BAND"):
        out.append(f"#define {k}_C {float(getattr(km, k))!r}")
    out.append(f"#define PIPE_ROUGHNESS_C {float(comp.PIPE_ROUGHNESS)!r}")
    out.append(f"#define STIFF_SUBDIV_C {int(km.STIFF_SUBDIV)}")
    out.append(f"#define MAX_SUBDIV_C {int(km.MAX_SUBDIV)}")
    if comp.KV_TO_C != 1.0 / 36000.0 or comp.BYPASS_CODE != 1 or comp.BYPASS_R != 50.0:
        raise RuntimeError("components constants changed: update hgbp_step.cu")
    lb = f"__launch_bounds__({launch_bounds[0]}, {launch_bounds[1]})" if launch_bounds else ""
    out.append(f"#define LAUNCH_BOUNDS {lb}")
    return "\n".join(out) + "\n"


def _wrap_literals(src: str) -> str:
    a, b = src.index("//@@DEVICE_BEGIN"), src.index("//@@DEVICE_END")
    return src[:a] + _LIT.sub(r"R(\1)", src[a:b]) + src[b:]


def _nvcc() -> str:
    home = os.environ.get("CUDA_HOME", "/usr/local/cuda")
    return str(Path(home) / "bin" / "nvcc")


def build(maxrregcount: int | None = None, fmad: bool = True, fastmath: bool = False,
          launch_bounds: tuple | None = None, arch: str = "native", verbose: bool = False) -> Path:
    """Compile the CUDA source (cached by content and options); returns the library path."""
    header = _header(launch_bounds)
    src = _wrap_literals(_SRC.read_text())
    flags = ["-O3", f"-arch={arch}", "-std=c++17", "-shared", "-Xcompiler", "-fPIC", f"--fmad={str(fmad).lower()}"]
    if fastmath:
        flags.append("--use_fast_math")
    if maxrregcount:
        flags.append(f"-maxrregcount={int(maxrregcount)}")
    key = hashlib.sha256((header + src + " ".join(flags)).encode()).hexdigest()[:16]
    d = Path(os.environ.get("HGBP_CUDA_CACHE", Path.home() / ".cache" / "hgbp_sim" / "cuda")) / key
    lib = d / "libhgbp_step.so"
    if lib.exists():
        return lib
    d.mkdir(parents=True, exist_ok=True)
    (d / "hgbp_layout.h").write_text(header)
    (d / "hgbp_step.cu").write_text(src)
    cmd = [_nvcc(), *flags, "-I", str(d), "-o", str(d / "tmp.so"), str(d / "hgbp_step.cu")]
    if verbose:
        print(" ".join(cmd))
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError(f"nvcc failed:\n{r.stderr}")
    os.replace(d / "tmp.so", lib)
    return lib


_libs: dict = {}


def load(**opts) -> ctypes.CDLL:
    path = build(**opts)
    if path in _libs:
        return _libs[path]
    lib = ctypes.CDLL(str(path))
    vp, i, d, dp, ip = ctypes.c_void_p, ctypes.c_int, ctypes.c_double, ctypes.POINTER(ctypes.c_double), \
        ctypes.POINTER(ctypes.c_int)
    lib.hg_error.restype = ctypes.c_char_p
    lib.hg_create.argtypes = [ctypes.POINTER(vp), i, i, i, dp, i, dp, i, dp, dp, dp, i, i, i, d, d, d, d]
    lib.hg_set_state.argtypes = [vp, dp, dp]
    lib.hg_get_state.argtypes = [vp, dp, dp, ip]
    lib.hg_get_stats.argtypes = [vp, ip]
    lib.hg_set_inputs.argtypes = [vp, dp, dp, dp, dp]
    lib.hg_set_order.argtypes = [vp, ip]
    lib.hg_step.argtypes = [vp, d, i, i, i, i, ctypes.POINTER(ctypes.c_float)]
    lib.hg_nrhs.argtypes = [vp, ctypes.POINTER(ctypes.c_ulonglong)]
    lib.hg_kernel_info.argtypes = [i, ip, ip, ip]
    lib.hg_destroy.argtypes = [vp]
    _libs[path] = lib
    return lib


def _p(a, ct=ctypes.c_double):
    return a.ctypes.data_as(ctypes.POINTER(ct))


class CudaStep:
    """The model's step on the GPU for a batch of ``len(rec)`` stands: parameter records
    ``rec`` (``layout.PARAM_DTYPE``, as ``plant.p.packed()``), property tables ``tab``
    (``RefrigerantTables.tab``), step ``dt`` and ``integrator`` as the plant's.  State and
    inputs are copied in and out explicitly; between the calls they stay on the device."""

    STATS = ("substeps", "retry1", "retry2", "suction_unconverged", "flash_unconverged")

    def __init__(self, rec, tab, dt: float = 0.05, integrator: str = "rk4", mode: str = "fp64", device: int = 0,
                 block: int = 128, **build_opts):
        self.lib = load(**build_opts)
        self.mode = mode
        self.n = len(rec)
        self.dt = float(dt)
        self.integrator = km.INTEGRATORS[integrator]
        self.block = int(block)
        params = np.ascontiguousarray(rec).view(np.float64).reshape(self.n, -1)
        t = tab
        self._keep = [np.ascontiguousarray(a, dtype=np.float64) for a in (params, t.sat, t.tr, t.vap, t.liq)]
        pa, sat, tr, vap, liq = self._keep
        h = ctypes.c_void_p()
        self._ck(self.lib.hg_create(ctypes.byref(h), int(device), self.n, MODES[mode], _p(pa), pa.shape[1],
                                    _p(sat), sat.shape[0], _p(tr), _p(vap), _p(liq), vap.shape[0], int(t.n_p),
                                    int(t.n_z), float(t.lp0), float(t.inv_dlp), float(t.p_min), float(t.p_max)))
        self.h = h
        self.stats = np.zeros((6, self.n), np.int32)

    @classmethod
    def for_plant(cls, plant, **kw) -> "CudaStep":
        """For the stands of an :class:`hgbp_sim.plant.HGBPPlant`."""
        return cls(plant.p.packed(), plant.props.tab, plant.dt, plant.integrator, **kw)

    def _ck(self, r):
        if r != 0:
            raise RuntimeError(self.lib.hg_error().decode())

    def set_state(self, x, lam) -> None:
        x = np.ascontiguousarray(x, dtype=np.float64)
        lam = np.ascontiguousarray(lam, dtype=np.float64)
        self._ck(self.lib.hg_set_state(self.h, _p(x), _p(lam)))

    def get_state(self):
        """(x (n, NX), lam (n,), stats dict of the last launch)"""
        x = np.empty((self.n, L.NX))
        lam = np.empty(self.n)
        self._ck(self.lib.hg_get_state(self.h, _p(x), _p(lam), _p(self.stats, ctypes.c_int)))
        return x, lam, {k: self.stats[i].copy() for i, k in enumerate(self.STATS)}

    def get_stats(self) -> np.ndarray:
        """(6, n) counters of the last launch (rows as ``STATS``)."""
        self._ck(self.lib.hg_get_stats(self.h, _p(self.stats, ctypes.c_int)))
        return self.stats

    def set_inputs(self, u_cmd, N_cmd, T_amb, T_wi) -> None:
        n = self.n
        a = [np.ascontiguousarray(np.broadcast_to(np.asarray(v, float), s))
             for v, s in ((u_cmd, (n, 4)), (N_cmd, (n,)), (T_amb, (n,)), (T_wi, (n,)))]
        self._ck(self.lib.hg_set_inputs(self.h, *(_p(v) for v in a)))

    def set_order(self, order=None) -> None:
        """Thread -> stand permutation (e.g. stands sorted by their sub-step count); None: identity."""
        if order is None:
            self._ck(self.lib.hg_set_order(self.h, None))
        else:
            o = np.ascontiguousarray(order, dtype=np.int32)
            self._ck(self.lib.hg_set_order(self.h, _p(o, ctypes.c_int)))

    def step(self, n_ctrl: int = 1, n_sub: int = 5) -> float:
        """``n_ctrl`` launches of ``n_sub`` steps of ``dt`` each; returns the GPU time [s]."""
        ms = ctypes.c_float()
        self._ck(self.lib.hg_step(self.h, self.dt, int(n_sub), self.integrator, int(n_ctrl), self.block,
                                  ctypes.byref(ms)))
        return ms.value * 1e-3

    def n_rhs(self) -> int:
        v = ctypes.c_ulonglong()
        self._ck(self.lib.hg_nrhs(self.h, ctypes.byref(v)))
        return int(v.value)

    def kernel_info(self) -> dict:
        r, lb, mt = ctypes.c_int(), ctypes.c_int(), ctypes.c_int()
        self._ck(self.lib.hg_kernel_info(MODES[self.mode], ctypes.byref(r), ctypes.byref(lb), ctypes.byref(mt)))
        return {"registers": r.value, "local_bytes": lb.value, "max_threads_per_block": mt.value}

    def close(self) -> None:
        if getattr(self, "h", None):
            self.lib.hg_destroy(self.h)
            self.h = None

    def __del__(self):
        try:
            self.close()
        except Exception:
            pass
